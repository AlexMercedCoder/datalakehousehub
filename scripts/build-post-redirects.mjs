#!/usr/bin/env node
/**
 * Writes 301s from every post's older URLs to its current /blog/<slug>/ URL.
 *
 * A post's URL is its `slug:` frontmatter when set, otherwise its content id
 * (the file path). Posts were reachable at /blog/<file-name>/, at
 * /blog/<year>/<file-name>/, and at /posts/<file-name>/ before slugs were
 * added, and Google still crawls those. This runs before every build, so a
 * new post or a slug change is covered automatically.
 *
 * The generated block lives between markers in public/_redirects, after the
 * alias-domain block and before the generic /posts/* rule, so specific rules
 * win and nothing chains into a 404.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, basename, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BLOG = join(ROOT, 'src/content/blog');
const FILE = join(ROOT, 'public/_redirects');
const START = '# post-redirects:start (generated by scripts/build-post-redirects.mjs; do not edit)';
const END = '# post-redirects:end';

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : /\.mdx?$/.test(name) ? [full] : [];
  });
}

const rules = new Map();
for (const file of walk(BLOG)) {
  const fm = readFileSync(file, 'utf8').match(/^---\s*\n([\s\S]*?)\n---/)?.[1] ?? '';
  const slug = fm.match(/^slug:\s*["']?([^"'\n]+?)["']?\s*$/m)?.[1];
  const id = relative(BLOG, file).replace(/\.mdx?$/, '');
  // Without a slug the post lives at its content id (/blog/<year>/<file-name>/).
  const target = `/blog/${(slug ?? id).toLowerCase()}/`;
  const name = basename(id);
  // Netlify matches rules case-sensitively, so emit original-case and lowercase forms.
  const olds = new Set([`/blog/${name}`, `/blog/${id}`, `/posts/${name}`, `/posts/${id}`].flatMap((p) => [p, p.toLowerCase()]));
  for (const old of olds) {
    if (old === target.slice(0, -1)) continue;
    rules.set(old, target);
  }
}

// Posts deleted in favor of a newer version; old file name -> current slug.
const REPLACED = {
  '2026-05-agentic-coding-tools': 'agentic-coding-tools',
  // Consolidated into the Aug 19 primaries (Oct 2026 maintenance pass).
  '2026-08-25-serverless-iceberg-microbatch-pyiceberg-duckdb': 'serverless-iceberg-ingestion-pyiceberg-duckdb',
  '2026-08-serverless-iceberg-microbatch-pyiceberg-duckdb': 'serverless-iceberg-ingestion-pyiceberg-duckdb',
  '2026-08-25-zero-copy-legacy-db-to-iceberg': 'zero-copy-warehouse-modernization-iceberg',
  '2026-08-zero-copy-legacy-db-to-iceberg': 'zero-copy-warehouse-modernization-iceberg',
};
for (const [old, slug] of Object.entries(REPLACED)) {
  for (const prefix of ['/blog/', '/posts/', '/blog/2026/']) rules.set(`${prefix}${old}`, `/blog/${slug}/`);
}

const block = [
  START,
  `# ${rules.size} old post URL(s) -> current slug URLs`,
  ...[...rules].sort().map(([from, to]) => `${from}  ${to}  301!`),
  END,
].join('\n');

let text = readFileSync(FILE, 'utf8');
text = text.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}\\n?`), '');
const aliasEnd = '# alias-redirects:end\n';
text = text.includes(aliasEnd) ? text.replace(aliasEnd, `${aliasEnd}${block}\n`) : `${block}\n${text}`;
writeFileSync(FILE, text);
console.log(`post-redirects: ${rules.size} rules written to public/_redirects`);
